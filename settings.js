const languageSelect = document.querySelector('[data-language-select]');
const settingsMenu = document.querySelector('.settings-menu');
const savedLanguage = localStorage.getItem('wifi-wiki-language') || 'es';

function applyInterfaceLanguage(language) {
  const translations = interfaceTranslations[language];
  document.documentElement.lang = language;
  if (languageSelect) languageSelect.value = language;
  if (!translations) return;
  window.translateText = text => translations[text] || text;
  document.title = translations[document.title] || document.title;
  const description = document.querySelector('meta[name="description"]');
  if (description && translations[description.content]) description.content = translations[description.content];

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const original = node.nodeValue.trim();
    if (!original || !translations[original]) continue;
    const leading = node.nodeValue.match(/^\s*/)[0];
    const trailing = node.nodeValue.match(/\s*$/)[0];
    node.nodeValue = `${leading}${translations[original]}${trailing}`;
  }

  document.querySelectorAll('input[placeholder]').forEach(input => {
    if (translations[input.placeholder]) input.placeholder = translations[input.placeholder];
  });
  document.querySelectorAll('[aria-label]').forEach(element => {
    if (translations[element.getAttribute('aria-label')]) {
      element.setAttribute('aria-label', translations[element.getAttribute('aria-label')]);
    }
  });
  document.querySelectorAll('[title]').forEach(element => {
    if (translations[element.title]) element.title = translations[element.title];
  });
}

applyInterfaceLanguage(savedLanguage);
document.dispatchEvent(new CustomEvent('site-language-applied', { detail: { language: savedLanguage } }));
languageSelect?.addEventListener('change', () => {
  localStorage.setItem('wifi-wiki-language', languageSelect.value);
  window.location.reload();
});

document.querySelectorAll('[data-print-page]').forEach(button => {
  button.addEventListener('click', () => {
    if (settingsMenu) settingsMenu.open = false;
    window.print();
  });
});
